// Antigravity 没带调试端口启动时，问要不要关掉它、再带参数重新打开（v2.0，插件模式）。
// 背景：Antigravity 2.33.0 起，只有带 --remote-debugging-port 启动才打开调试端口，注入程序要靠它改界面。
// Windows 上安装程序给快捷方式加了参数，但自动更新后自己重启、或者从别的入口打开时会不带；macOS 从程序坞打开总是不带。
// sidecar 由 Antigravity 的后台启动，跟调试端口无关，所以这时它照样在运行，可以帮忙重开。
// - 调试端口连续 20 秒连不上（注入程序的 portState），而且这次启动（按 ANTIGRAVITY_LS_ADDRESS 区分）还没问过：
//   按设置 relaunch 处理：ask（默认）弹框问；auto 直接重开；never 不管。设置存在数据目录的 settings.json，侧边栏面板里改。
//   例外：2 分钟内已经重开过一次（手动或自动），auto 也改成弹框问——重开后端口还是没有（残留进程、参数没吃上）时，
//   自动重开只会每隔约 25 秒反复重启；改成问，由你决定（也可能是你刚自己从程序坞不带参数打开，这时照样该问）。
// - 重开：关掉 Antigravity，几秒后还没退出就强制结束，再带 --remote-debugging-port=0 打开。
//   sidecar 是 Antigravity 的子进程，Antigravity 一关它也会被关掉，所以干这件事的脚本要脱离 Antigravity 运行：
//   Windows 见下面的 WIN_SCRIPT（交给资源管理器或 WMI 去启动，不在 Antigravity 的作业对象里）；
//   macOS 上用 nohup 在后台跑 /bin/sh 脚本（马上脱离 sidecar）：quit app → 等退出 → open -a … --args --remote-debugging-port=0。
//   子进程一律用去掉 ELECTRON_RUN_AS_NODE 等变量的环境（cleanEnv）。每一步记进数据目录的 relaunch.log。
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';

const IS_WIN = process.platform === 'win32';
const IS_MAC = process.platform === 'darwin';
const DEBUG_ARG = '--remote-debugging-port=0';
const PROMPT_AFTER_MS = 20000;
const MODES = ['ask', 'auto', 'never'];

const readJson = (f, d) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return d; } };
const writeJson = (f, o) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, JSON.stringify(o, null, 2)); };
const settingsFile = (ctx) => path.join(ctx.dataDir, 'settings.json');
const stateFile = (ctx) => path.join(ctx.dataDir, 'relaunch-state.json');

export const getMode = (ctx) => { const m = readJson(settingsFile(ctx), {}).relaunch; return MODES.includes(m) ? m : 'ask'; };
export function setMode(ctx, mode) {
  if (!MODES.includes(mode)) throw Error('bad mode');
  writeJson(settingsFile(ctx), { ...readJson(settingsFile(ctx), {}), relaunch: mode });
  ctx.zh.log(`relaunch mode: ${mode}`);
}

// 要重新打开的 Antigravity：Windows 上 sidecar 本身就是以 Node 模式运行的 Antigravity.exe；macOS 上从 Helper 的路径往上找 .app
export function targetApp() {
  if (IS_WIN) {
    if (/\\antigravity\.exe$/i.test(process.execPath)) return process.execPath;
    const def = path.join(process.env.LOCALAPPDATA || '', 'Programs', 'antigravity', 'Antigravity.exe');
    return fs.existsSync(def) ? def : '';
  }
  if (IS_MAC) {
    const m = /^(.*?\.app)\//.exec(process.execPath);
    if (m && fs.existsSync(m[1])) return m[1];
    for (const p of ['/Applications/Antigravity.app', path.join(os.homedir(), 'Applications', 'Antigravity.app')]) if (fs.existsSync(p)) return p;
  }
  return '';
}

export function info(ctx) {
  const st = readJson(stateFile(ctx), {});
  return { mode: getMode(ctx), target: targetApp(), lastPromptAt: st.lastPromptAt || 0, lastRelaunchAt: st.lastRelaunchAt || 0, supported: IS_WIN || IS_MAC };
}

// 子进程用的环境变量：sidecar 是 Node 模式的 Antigravity（ELECTRON_RUN_AS_NODE=1），还带着 Antigravity 给 sidecar 的变量。
// 这些要去掉，不然重开的 Antigravity 会继承 ELECTRON_RUN_AS_NODE，以 Node 模式运行、不出窗口。
const DROP_ENV = /^(ELECTRON_|NODE_|ANTIGRAVITY_|AGY_|VSCODE_)/i;
function cleanEnv(extra = {}) {
  const env = {};
  for (const [k, v] of Object.entries(process.env)) if (!DROP_ENV.test(k)) env[k] = v;
  return { ...env, ...extra };
}
// 重开过程的每一步记进数据目录的 relaunch.log（超过 64 KB 就清空重记）
function relaunchLog(ctx) {
  const f = path.join(ctx.dataDir, 'relaunch.log');
  try { if (fs.statSync(f).size > 65536) fs.writeFileSync(f, ''); } catch {}
  return f;
}

// Windows 的重开脚本（写进数据目录的 relaunch-antigravity.ps1；只用 ASCII，PowerShell 5.1 不会读错）。
// 为什么要分两段：sidecar 和它直接启动的进程都在 Antigravity 的作业对象（Job Object）里，Antigravity 退出时会被一起结束，
// 所以真正干活的 relaunch 段必须由作业对象外面的进程启动。launch 段依次试三条路：
//   explorer  让桌面所在的 explorer.exe 去 ShellExecute（经 Shell.Application.Windows() 找到桌面视图），新进程是 explorer 的子进程；
//   wmi       用 WMI 的 Win32_Process.Create，新进程由 WMI 服务创建；
//   direct    直接 Start-Process（还在作业对象里，Antigravity 退出时可能被一起结束，只是最后的退路）。
// ShellExecute 不返回成败，所以每条路都要等回执：relaunch 段一启动就写一个标记文件，8 秒内没出现就试下一条路。
// 先走的那条路晚到时可能有两份 relaunch 段：用命名互斥锁保证同一时间只有一份干活；干完的那份写“已完成”标记，
// 更晚才起来的看到标记就退出，不会把刚打开的 Antigravity 再关一次。relaunch 段出错时写进日志。
// relaunch 段：请 Antigravity 主窗口正常关闭，最多等 15 秒，还有进程没退出就强制结束，再带 --remote-debugging-port=0 打开。
// 进程一律按 WMI 的 ExecutablePath 找（不用打开进程，不会因为权限报错）；路径用 .NET 函数处理（不把 [ ] 当通配符）。
// 注意：PowerShell 函数返回只有一个元素的数组时会被拆成单个对象，单个 WMI 对象没有 .Count，
// 所以调用这几个函数的地方一律包 @()（11-23 真机重开时日志里进程数是空的，只剩一个进程时等待循环会提前结束）。
// 原来快捷方式上的其他启动参数不会带上（只带调试端口参数）。
// 每一步记进 relaunch.log。-DryRun（测试用）时 relaunch 段只记下自己的进程号、父进程和是否在作业对象里，不动 Antigravity。
// -Route 可以写几条路，用逗号隔开（测试用；none = 什么都不启动，用来测等不到回执时换路）。
const WIN_SCRIPT = String.raw`# agy-zh-pack: restart Antigravity with --remote-debugging-port=0 (generated by lib/relaunch.mjs)
param(
  [string]$Stage = 'launch',
  [string]$Target,
  [string]$Log,
  [string]$Route = '',
  [string]$Token = '',
  [switch]$DryRun
)
$ErrorActionPreference = 'Stop'

function Write-Note([string]$Text) {
  try { [IO.File]::AppendAllText($Log, (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + ' [' + $Stage + '] ' + $Text + [Environment]::NewLine) } catch { }
}
function Get-MarkerPath([string]$Id, [string]$Kind = 'started') {
  [IO.Path]::Combine([IO.Path]::GetDirectoryName($Log), 'relaunch-' + $Id + '.' + $Kind)
}

$selfPath = $MyInvocation.MyCommand.Path
$powershell = [IO.Path]::Combine($PSHOME, 'powershell.exe')

if ($Stage -eq 'launch') {
  # markers left by earlier runs
  try {
    Get-ChildItem -LiteralPath ([IO.Path]::GetDirectoryName($Log)) -Filter 'relaunch-*.*' |
      Where-Object { $_.Name -match '^relaunch-[0-9a-f]+.(started|done)$' -and $_.LastWriteTime -lt (Get-Date).AddMinutes(-10) } |
      ForEach-Object { Remove-Item -LiteralPath $_.FullName -Force -ErrorAction SilentlyContinue }
  } catch { }
  $Token = [Guid]::NewGuid().ToString('N')
  $marker = Get-MarkerPath $Token
  $line = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + $selfPath + '" -Stage relaunch -Target "' + $Target + '" -Log "' + $Log + '" -Token ' + $Token
  if ($DryRun) { $line += ' -DryRun' }
  $routes = if ($Route) { $Route.Split(',') } else { @('explorer', 'wmi', 'direct') }
  foreach ($r in $routes) {
    try {
      switch ($r) {
        'explorer' {
          $windows = (New-Object -ComObject Shell.Application).Windows()
          $handle = 0
          $desktop = $windows.FindWindowSW(0, 0, 8, [ref]$handle, 1)   # 8 = SWC_DESKTOP, 1 = SWFO_NEEDDISPATCH
          if ($null -eq $desktop) { throw 'desktop window not found' }
          $desktop.Document.Application.ShellExecute($powershell, $line, $PSHOME, 'open', 0)
        }
        'wmi' {
          $result = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = ('"' + $powershell + '" ' + $line) }
          if ($result.ReturnValue -ne 0) { throw ('Win32_Process.Create returned ' + $result.ReturnValue) }
        }
        'direct' {
          Start-Process -FilePath $powershell -ArgumentList $line -WindowStyle Hidden
        }
        'none' { }
        default { throw ('unknown route ' + $r) }
      }
    } catch {
      Write-Note ($r + ' failed: ' + $_.Exception.Message)
      continue
    }
    $deadline = (Get-Date).AddSeconds(8)
    while (-not [IO.File]::Exists($marker) -and (Get-Date) -lt $deadline) { Start-Sleep -Milliseconds 100 }
    if ([IO.File]::Exists($marker)) {
      Write-Note ('handed over via ' + $r)
      try { [IO.File]::Delete($marker) } catch { }
      exit 0
    }
    Write-Note ($r + ': no sign of the relaunch script after 8 s, trying the next way')
  }
  Write-Note 'gave up: the relaunch script could not be started'
  exit 1
}

# ---- relaunch stage ----
trap { Write-Note ('error: ' + $_.Exception.Message); exit 1 }
if ($Token) { try { [IO.File]::WriteAllText((Get-MarkerPath $Token), [string]$PID) } catch { } }
$mutex = New-Object Threading.Mutex($false, 'Local\agy-zh-pack-relaunch')
$owned = $false
try { $owned = $mutex.WaitOne(0) } catch [Threading.AbandonedMutexException] { $owned = $true }
if (-not $owned) {
  Write-Note ('another relaunch script is already running, pid=' + $PID + ' exits')
  exit 0
}
if ($Token -and [IO.File]::Exists((Get-MarkerPath $Token 'done'))) {
  Write-Note ('this relaunch was already done by another copy, pid=' + $PID + ' exits')
  exit 0
}
foreach ($name in 'ELECTRON_RUN_AS_NODE', 'ELECTRON_NO_ATTACH_CONSOLE', 'NODE_OPTIONS', 'NODE_PATH') {
  [Environment]::SetEnvironmentVariable($name, $null, 'Process')
}
$parentName = 'unknown'
try {
  $me = Get-CimInstance Win32_Process -Filter ('ProcessId=' + $PID)
  $parent = Get-CimInstance Win32_Process -Filter ('ProcessId=' + $me.ParentProcessId) -ErrorAction SilentlyContinue
  $parentName = if ($parent) { $parent.Name } else { 'gone' }
} catch { }

if ($DryRun) {
  Add-Type -Namespace AgyZh -Name Job -MemberDefinition '[DllImport("kernel32.dll")] public static extern bool IsProcessInJob(IntPtr process, IntPtr job, out bool result);'
  $inJob = $false
  [void][AgyZh.Job]::IsProcessInJob([Diagnostics.Process]::GetCurrentProcess().Handle, [IntPtr]::Zero, [ref]$inJob)
  Write-Note ('dry run: pid=' + $PID + ' parent=' + $parentName + ' inJob=' + $inJob)
  Start-Sleep -Seconds 1
  exit 0
}

Write-Note ('pid=' + $PID + ' parent=' + $parentName)
$exeName = [IO.Path]::GetFileName($Target)
function Get-AntigravityProcs {
  @(Get-CimInstance Win32_Process -Filter ("Name='" + $exeName + "'") | Where-Object { $_.ExecutablePath -eq $Target })
}
function Get-AntigravityMain {
  # main window process: not a helper (--type=), not Antigravity run as Node (plugin sidecars use --import=, the installer runs setup.mjs)
  @(Get-AntigravityProcs | Where-Object { $_.CommandLine -notmatch '--type=|--import=|[\\/]setup\.mjs' })
}
function Wait-AllGone([int]$Seconds) {
  $deadline = (Get-Date).AddSeconds($Seconds)
  while (@(Get-AntigravityProcs).Count -and (Get-Date) -lt $deadline) { Start-Sleep -Milliseconds 300 }
  Get-AntigravityProcs
}

Start-Sleep -Milliseconds 500   # let the sidecar answer the panel first
$main = @(Get-AntigravityMain)
Write-Note ('asking Antigravity to close, main processes: ' + $main.Count)
foreach ($m in $main) {
  try { [void][Diagnostics.Process]::GetProcessById([int]$m.ProcessId).CloseMainWindow() } catch { }
}
$left = @(Wait-AllGone 15)
if ($left.Count) {
  Write-Note ('still running after 15 s (' + $left.Count + ' processes), ending them')
  foreach ($m in $left) { try { Stop-Process -Id $m.ProcessId -Force -ErrorAction Stop } catch { } }
  $left = @(Wait-AllGone 5)
  if ($left.Count) { Write-Note ('warning: ' + $left.Count + ' Antigravity processes are still running, the new window may not get the debug port') }
}
Start-Sleep -Milliseconds 300
try {
  $psi = New-Object Diagnostics.ProcessStartInfo
  $psi.FileName = $Target
  $psi.Arguments = '--remote-debugging-port=0'
  $psi.WorkingDirectory = [IO.Path]::GetDirectoryName($Target)
  $psi.UseShellExecute = $true
  [void][Diagnostics.Process]::Start($psi)
  Write-Note 'Antigravity started with the debug port'
} catch {
  Write-Note ('start failed: ' + $_.Exception.Message)
}
if ($Token) {
  try { [IO.File]::WriteAllText((Get-MarkerPath $Token 'done'), [string]$PID) } catch { }
  try { [IO.File]::Delete((Get-MarkerPath $Token)) } catch { }
}
Remove-Item -LiteralPath $selfPath -Force -ErrorAction SilentlyContinue
`;

export function relaunchNow(ctx) {
  const target = targetApp();
  if (!target) throw Error('没找到 Antigravity 的程序文件');
  writeJson(stateFile(ctx), { ...readJson(stateFile(ctx), {}), lastRelaunchAt: Date.now() });
  ctx.zh.log(`relaunching Antigravity with ${DEBUG_ARG}: ${target}`);
  const logFile = relaunchLog(ctx);
  if (IS_WIN) {
    // 一个脚本分两段跑（见 WIN_SCRIPT）：launch 段由 sidecar 直接启动（还在 Antigravity 的作业对象里），
    // 只负责把 relaunch 段交给作业对象外面的进程去跑；relaunch 段关掉 Antigravity、再带参数打开。
    const script = path.join(ctx.dataDir, 'relaunch-antigravity.ps1');
    fs.writeFileSync(script, '\uFEFF' + WIN_SCRIPT.replace(/\n/g, '\r\n'), 'utf8');
    const args = ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', script,
      '-Stage', 'launch', '-Target', target, '-Log', logFile];
    if (process.env.AGY_ZH_RELAUNCH_DRYRUN === '1') args.push('-DryRun'); // 测试用：不动 Antigravity，只记下 relaunch 段在哪个进程里跑
    if (process.env.AGY_ZH_RELAUNCH_ROUTE) args.push('-Route', process.env.AGY_ZH_RELAUNCH_ROUTE); // 测试用：只试指定的那条路
    const child = spawn(path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe'), args,
      { stdio: 'ignore', windowsHide: true, env: cleanEnv() });
    child.on('error', (e) => ctx.zh.log('relaunch: could not start powershell: ' + e.message));
    child.unref();
    return { scheduled: true, target };
  }
  if (IS_MAC) {
    // 脚本写进数据目录，用 nohup 放到后台跑，外层 sh 马上退出：脚本立刻变成 launchd 的子进程，
    // 不再挂在 sidecar 底下，Antigravity 退出、连带结束 sidecar 的子进程时不会把它一起结束。
    const script = path.join(ctx.dataDir, 'relaunch-antigravity.sh');
    const pat = '"$AGY_APP/Contents/MacOS/Antigravity"';
    const body = [
      '#!/bin/sh',
      'unset ELECTRON_RUN_AS_NODE ELECTRON_NO_ATTACH_CONSOLE NODE_OPTIONS NODE_PATH',
      'L() { echo "$(date "+%Y-%m-%d %H:%M:%S") $*" >> "$AGY_LOG"; }',
      'L "script start pid=$$ ppid=$PPID"',
      'sleep 0.5',
      `L "closing, running=$(pgrep -f ${pat} | wc -l | tr -d ' ')"`,
      'osascript -e "quit app \\"$AGY_APP\\"" >/dev/null 2>&1',
      `i=0; while [ $i -lt 40 ] && pgrep -f ${pat} >/dev/null; do sleep 0.25; i=$((i+1)); done`,
      `if pgrep -f ${pat} >/dev/null; then L "force kill"; pkill -f ${pat} >/dev/null 2>&1; fi`,
      `i=0; while [ $i -lt 24 ] && pgrep -f ${pat} >/dev/null; do sleep 0.25; i=$((i+1)); done`,
      'sleep 0.5',
      `open -a "$AGY_APP" --args ${DEBUG_ARG}; L "open exit=$?"`,
      'rm -f "$0"',
    ].join('\n');
    fs.writeFileSync(script, body + '\n');
    const child = spawn('/bin/sh', ['-c', 'nohup /bin/sh "$1" </dev/null >/dev/null 2>&1 &', 'sh', script],
      { detached: true, stdio: 'ignore', env: cleanEnv({ AGY_APP: target, AGY_LOG: logFile }) });
    child.on('error', (e) => ctx.zh.log('relaunch: could not start sh: ' + e.message));
    child.unref();
    return { scheduled: true, target };
  }
  throw Error('这个系统不支持自动重开');
}

const MESSAGE = '这次 Antigravity 启动时没带调试端口参数（--remote-debugging-port=0），agy-zh 的汉化和用量状态栏暂时没生效。\n\n' +
  '要现在重启 Antigravity 吗？对话记录会保留，正在运行的任务会被打断。\n\n' +
  '（在侧边栏“agy-zh”面板里可以改成以后自动重开，或者不再询问。）';
// 弹框问；用户点了“重启”就调 yes()
function ask(ctx, yes) {
  if (IS_WIN) {
    const child = spawn('powershell.exe', ['-NoProfile', '-NonInteractive', '-WindowStyle', 'Hidden', '-Command',
      '$r = (New-Object -ComObject WScript.Shell).Popup($env:AGY_ZH_MSG, 0, "agy-zh", 1 + 32 + 4096); if ($r -eq 1) { exit 10 } else { exit 0 }'],
    { stdio: 'ignore', windowsHide: true, env: cleanEnv({ AGY_ZH_MSG: MESSAGE }) }); // 1 确定/取消，32 问号，4096 置顶
    child.on('error', (e) => ctx.zh.log('relaunch: could not show the question: ' + e.message));
    child.on('exit', (code) => { if (code === 10) yes(); else ctx.zh.log('relaunch declined'); });
    return;
  }
  if (IS_MAC) {
    const script = `display dialog ${JSON.stringify(MESSAGE)} with title "agy-zh" buttons {"稍后", "立即重启"} default button "立即重启" with icon caution`;
    const child = spawn('osascript', ['-e', script], { stdio: ['ignore', 'pipe', 'ignore'], env: cleanEnv() });
    let out = '';
    child.stdout.on('data', (c) => { out += c; });
    child.on('error', (e) => ctx.zh.log('relaunch: could not show the question: ' + e.message));
    child.on('exit', (code) => { if (code === 0 && out.includes('立即重启')) yes(); else ctx.zh.log('relaunch declined'); });
  }
}

export function startRelaunchWatch(ctx) {
  if (!IS_WIN && !IS_MAC) return;
  const timer = setInterval(() => {
    try {
      const st = ctx.zh.status();
      if (!st.lockHeld || st.port.ok !== false || Date.now() - st.port.since < PROMPT_AFTER_MS) return;
      const mode = getMode(ctx);
      if (mode === 'never') return;
      const key = process.env.ANTIGRAVITY_LS_ADDRESS || `ppid-${process.ppid}`; // 这次启动
      const state = readJson(stateFile(ctx), {});
      if (state.promptedFor === key) return;
      const recent = Date.now() - (state.lastRelaunchAt || 0) < 120000; // 见文件头的“例外”
      writeJson(stateFile(ctx), { ...state, promptedFor: key, lastPromptAt: Date.now() });
      ctx.zh.log(`no debug port for ${Math.round((Date.now() - st.port.since) / 1000)}s, relaunch mode ${mode}` +
        (recent && mode === 'auto' ? ', relaunched less than 2 minutes ago: asking instead' : ''));
      const go = () => { try { relaunchNow(ctx); } catch (e) { ctx.zh.log(`relaunch failed: ${e.message}`); } };
      if (mode === 'auto' && !recent) go(); else ask(ctx, go);
    } catch (e) { ctx.zh.log(`relaunch watch error: ${e.message}`); }
  }, 5000);
  timer.unref();
}

